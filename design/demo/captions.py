SCRIPTS = {"reliability": RELIABILITY, "group-class": GROUP_CLASS, "overview": OVERVIEW}


def timeline(CUES):
    at = 0
    for act, cues in CUES:
        for dur, text in cues:
            yield at, at + dur, act, text
            at += dur


def stamp(seconds):
    ms = int(seconds * 1000)
    h, ms = divmod(ms, 3_600_000)
    m, ms = divmod(ms, 60_000)
    s, ms = divmod(ms, 1000)
    return f"{h:02}:{m:02}:{s:02},{ms:03}"


def srt(CUES):
    for i, (start, end, _act, text) in enumerate(timeline(CUES), 1):
        print(f"{i}\n{stamp(start)} --> {stamp(end)}\n{text}\n")


def review(CUES):
    act_now = None
    over = 0
    for start, _end, act, text in timeline(CUES):
        if act != act_now:
            act_now = act
            print(f"\n== {act}  ({stamp(start)})")
        longest = max(len(line) for line in text.split("\n"))
        flag = "  ← 太長" if longest > LIMIT else ""
        if longest > LIMIT:
            over += 1
        print(f"  {stamp(start)}  {text.splitlines()[0]}{flag}")
    total = sum(d for _, cues in CUES for d, _ in cues)
    budget = "" if total <= TARGET else f"  ← 超出目標 {total - TARGET} 秒"
    print(f"\n總長 {total // 60} 分 {total % 60} 秒 / 目標 {TARGET} 秒{budget}")
    print(f"{sum(len(c) for _, c in CUES)} 則字幕，{over} 則超過 {LIMIT} 字")


if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if a != "--srt"]
    name = args[0] if args else "reliability"
    if name not in SCRIPTS:
        sys.exit(f"沒有這支影片：{name}（可用：{', '.join(SCRIPTS)}）")
    cues = SCRIPTS[name]
    srt(cues) if "--srt" in sys.argv else review(cues)
